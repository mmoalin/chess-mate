// npm install --prefix outputs/game-review/db-runtime --no-package-lock @electric-sql/pglite
import { PGlite } from '../outputs/game-review/db-runtime/node_modules/@electric-sql/pglite/dist/index.js';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const db = new PGlite();
await db.exec(`create role authenticated; create role anon; create schema auth;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true),'')::uuid $$;
grant usage on schema auth to authenticated, anon; grant execute on function auth.uid() to authenticated, anon;
insert into auth.users values ('11111111-1111-4111-8111-111111111111'),('22222222-2222-4222-8222-222222222222');`);
await db.exec(readFileSync('supabase/migrations/202609260001_game_review.sql', 'utf8'));
let activeOwner;
const owner = async (id) => { activeOwner=id; await db.exec(`reset role; set role authenticated; select set_config('request.jwt.claim.sub','${id}',false);`); };
const a = '11111111-1111-4111-8111-111111111111', b = '22222222-2222-4222-8222-222222222222';
const write = async (kind, id, value, revision = 0, deleted = false, mutation = crypto.randomUUID()) => (await db.query('select * from public.write_game_review_record($1::uuid,$2,$3,$4::jsonb,$5,$6::uuid,$7)', [activeOwner, kind, id, JSON.stringify({ schema:1, id, ...value }), revision, mutation, deleted])).rows[0];
const checks = [];
await owner(a);
const mutation = crypto.randomUUID();
const first = await write('game','g',{ moves:['e2e4'] },0,false,mutation);
assert.equal(first.revision,1); assert.equal((await write('game','g',{ moves:['e2e4'] },0,false,mutation)).revision,1); checks.push('Idempotent mutation retry');
await write('run','r',{gameId:'g'}); await write('position','p1',{runId:'r',error:'timeout'});
await write('position','p2',{runId:'r',evidence:{fen:'exact',depth:16}});
assert.equal((await write('position','p1',{runId:'r',evidence:{depth:16}},1)).revision,2);
assert.ok((await write('position','p2',{runId:'r',error:'timeout'},1)).value.evidence); checks.push('Independent positions merge and complete evidence survives errors');
await write('card','c',{gameId:'g'}); await write('session','s',{cardId:'c',move:'e4'});
assert.equal((await write('session','s',{cardId:'c',move:'d4'},0)).value.move,'e4');
await write('session','s',{cardId:'c',move:'e4',submittedAt:'now'},1);
assert.equal((await write('session','s',{cardId:'c',move:'d4'},2)).value.move,'e4'); checks.push('Revision conflicts and submitted answers immutable');
await write('game','g',{},1,true); assert.equal((await write('game','g',{moves:['d2d4']},0)).deleted,true);
assert.equal((await db.query("select count(*)::int as n from public.game_review_records where kind='card'")).rows[0].n,1); checks.push('Deletion tombstone wins; practice card retained');
await owner(b);
activeOwner=a; await assert.rejects(write('game','wrong-account',{}),/Account changed/); activeOwner=b; checks.push('Stale writes cannot cross an account switch');
assert.equal((await db.query('select * from public.game_review_records')).rows.length,0);
await assert.rejects(write('run','foreign',{gameId:'g'}),/Missing owned parent/);
await assert.rejects(db.exec("insert into public.game_review_records(user_id,kind,id,value,mutation_id) values ('11111111-1111-4111-8111-111111111111','game','attack','{}',gen_random_uuid())"),/permission denied/); checks.push('Cross-account SELECT, parent reference and direct write denied');
await db.exec('reset role; set role anon;');
await assert.rejects(db.query('select * from public.game_review_records'),/permission denied/);
await assert.rejects(write('game','anon',{}),/permission denied/); checks.push('Anonymous reads and writes denied');
await db.close(); mkdirSync('outputs/game-review',{recursive:true});
const report = { runtime:'PGlite disposable PostgreSQL', productionTouched:false, checks, passed:true };
writeFileSync('outputs/game-review/database-verification.json',JSON.stringify(report,null,2)+'\n'); console.log(report);
